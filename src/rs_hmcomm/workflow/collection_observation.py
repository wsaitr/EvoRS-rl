"""Observe an authorized image collection in individually attributed calls; never answer for it."""
import json
import re
from PIL import Image
from .native_benchmark_tools import NativeDetectionToolbox
from .benchmark_budget import BudgetTaskBoundRuntime


def collection_names(action):
    if set(action) != {'tool', 'assets', 'question'}:
        raise ValueError('inspect_collection requires exactly tool, assets and question')
    names = action['assets']
    if (not isinstance(names, list) or not 1 <= len(names) <= 32
            or any(not isinstance(name, str) or not name for name in names)
            or len(set(names)) != len(names)):
        raise ValueError('one to 32 distinct actual assets required')
    if not isinstance(action['question'], str) or not action['question'].strip():
        raise ValueError('nonempty observation question required')
    return names


class CollectionToolbox(NativeDetectionToolbox):
    def execute(self, action):
        if action.get('tool') != 'inspect_collection':
            return super().execute(action)
        names = collection_names(action)
        # Check the entire requested collection before spending any model calls.
        for name in names: self.path(name)
        observations = []
        for name in names:
            with Image.open(self.path(name)) as image:
                if image.mode not in {'RGB', 'RGBA', 'L', 'P'}:
                    raise ValueError('scientific raster requires native numeric tools')
                image = image.convert('RGB'); size = list(image.size)
                pid = f'benchmark-view-{len(self.policy.packets)}'
                self.policy.encode(image, artifact_id=pid, source_image_ref=str(self.path(name)),
                    roi=(0, 0, 1, 1), label=name)
            prompt = 'Inspect ONLY the single attached image. The original collection task is context, not a request to answer it. '+json.dumps({
                'original_collection_question': action['question'], 'actual_attached_asset': name})+\
                '\nDescribe the land use, structures or changes actually visible in THIS image in one or two concise sentences. State uncertainty. Do not count unobserved images, choose an answer option, output JSON, or repeat these instructions.'
            raw = self.policy.decide('visual', prompt, (pid,), output_format='text')
            if (not isinstance(raw, str) or not raw.strip()
                    or re.fullmatch(r'[A-Z](?:[.)])?', raw.strip(), flags=re.I)
                    or raw.strip().casefold() in {'visible facts and explicit uncertainty', 'actual listed asset name'}):
                raise ValueError('per-image observation must describe actual visible facts, not an option or template')
            row = {'asset': name, 'description': raw.strip(), 'original_image_size': size}
            observations.append(row)
            # Attribution is bound to the actual one-image call, never generated by the model.
            self.events.append({'kind': 'collection_observation_batch', 'asset_names': [name],
                'packet_ids': [pid], 'observations': [row], 'reference_used': False,
                'asset_attribution': 'host-bound to single actually attached image'})
        result = {'observations': observations, 'observed_assets': names,
            'visual_model_calls': len(names), 'reference_used': False,
            'complete_requested_collection': True, 'final_answer_generated_by_tool': False}
        self.events.append({'kind': 'executed_tool', 'action': action, 'output': result,
            'origin': 'actual separately attributed image observations; never reference traces'})
        return result


class CollectionRuntime(BudgetTaskBoundRuntime):
    toolbox_class = CollectionToolbox

    def tool_model_calls(self, action):
        if action.get('tool') == 'inspect_collection':
            return len(collection_names(action))
        return super().tool_model_calls(action)

    def public_task(self, task):
        public = super().public_task(task)
        return {**public, 'available_tools': [*public['available_tools'], {
            'tool': 'inspect_collection', 'assets': list(task['assets']),
            'required_fields': {'question': 'per-image visual facts needed for this task; aggregation is a later decision'},
            'output': 'separate asset-attributed observations for every requested image; one actual image per visual call; source attribution is fixed by the host'}],
            'collection_rule': 'A whole-collection count or comparison requires observing every relevant asset. Inspect only reads its named images; do not extrapolate the other images or count option letters as observations.'}

    def action_context(self, public, history, cost):
        context = super().action_context(public, history, cost)
        observed = set()
        for item in history:
            if 'result' not in item: continue
            action = item.get('action', {})
            if action.get('tool') == 'inspect': observed.update(action.get('assets', []))
            elif action.get('tool') == 'inspect_collection': observed.update(item['result']['observed_assets'])
        missing = [name for name in public['assets'] if name not in observed]
        return {**context, 'collection_observation_state': {
            'total_authorized_assets': len(public['assets']), 'actually_observed_assets': sorted(observed),
            'not_yet_observed_assets': missing,
            'inspect_all_remaining_model_calls_including_action': 1+len(missing),
            'no_answer_or_label_based_coverage': True}}
